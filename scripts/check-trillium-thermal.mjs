import assert from 'node:assert/strict';
import fs from 'node:fs';
import FLOWERS from '../data/trillium-flowering-history.json' with {type:'json'};
import CLIMATE from '../data/trillium-thermal-history.json' with {type:'json'};
import {REGIONS} from '../lib/trillium.mjs';
import {fitThermalModel,dailyHeatSeries,decideThermal,heatUnit,BASE_F,thermalArchiveDay} from '../lib/trillium-thermal.mjs';
assert.equal(CLIMATE.schemaVersion,1);
assert.equal(CLIMATE.model,'era5');
assert.equal(CLIMATE.variable,'temperature_2m_mean');
assert.equal(CLIMATE.baseHeatF,40);
assert.equal(Object.keys(CLIMATE.regions).length,7);
assert.equal(heatUnit(55),15);
assert.equal(heatUnit(32),0);
assert.equal(heatUnit(NaN),null);
assert.equal(dailyHeatSeries([42]),null,'partial historic spring invalid');
assert.equal(dailyHeatSeries(Array(122).fill(null)),null,'missing temperatures invalid');
const models={};
for(const region of REGIONS){
 const item=CLIMATE.regions[region.id];assert.ok(item,region.id);
 assert.deepEqual(item.coordinate,[region.lat,region.lon],'Thermal archive uses exact same representative regional station point');
 for(let year=2019;year<=2026;year++){
  const temps=item.years[year];assert.ok(Array.isArray(temps)&&temps.length===122,'Complete March–June archive for '+region.id+' '+year);
  assert.ok(temps.every(n=>typeof n==='number'&&Number.isFinite(n)&&n>-40&&n<120),'Expected daily F values');
  const heat=dailyHeatSeries(temps);assert.equal(heat.length,122);assert.ok(heat.at(-1)>heat[0],'Heat index should accumulate through spring');
  assert.ok(heat.every((n,i)=>i===0||n>=heat[i-1]),'Cumulative heat cannot decrease');
 }
 models[region.id]=fitThermalModel(FLOWERS,CLIMATE,region.id,2027);
 assert.ok(['validated','descriptive','limited'].includes(models[region.id].state),'Must publish honest backtest state');
 assert.ok(models[region.id].eligibleYears>=5,'Enough overlapping report and weather years for '+region.id);
 assert.ok(models[region.id].heatMae>=0 && models[region.id].calendarMae>=0);
 const today=thermalArchiveDay(CLIMATE,region.id,55,2027);
 assert.equal(today.n,8);
 assert.ok(today.low<=today.median&&today.median<=today.high);
}
assert.equal(models.southeast.state,'validated','Only use a calibrated reference where held-out heat timing beats the calendar');
for(const region of REGIONS.filter(r=>r.id!=='southeast'))assert.notEqual(models[region.id].state,'validated','Do not create a fake site or statewide weather bloom date for '+region.id);
assert.ok(models.southeast.heatMae<models.southeast.calendarMae,'Held-out timing must beat historical calendar');
assert.equal(models.southeast.heldOut.length,8);
const days=Array.from({length:22},(_,i)=>({date:new Date(Date.parse('2027-03-01T12:00:00Z')+i*86400000).toISOString().slice(0,10),meanF:50,kind:i<=14?'reanalysis':'forecast'}));
const nonPredictive=decideThermal({archive:CLIMATE,regionId:'central',year:2027,nowDate:'2027-03-15',daily:days,model:models.central});
assert.equal(nonPredictive.state,'tracking');
assert.equal(nonPredictive.currentHeat,150);
assert.equal(nonPredictive.forecastDays,7);
assert.equal(nonPredictive.forecastHeatAdded,70);
assert.equal(nonPredictive.thermalSignal,undefined,'No heat-derived date where model failed validation');
const withReference=decideThermal({archive:CLIMATE,regionId:'southeast',year:2027,nowDate:'2027-03-15',daily:days,model:{state:'validated',threshold:190,eligibleYears:8}});
assert.equal(withReference.thermalSignal.kind,'forecast_crossing');
assert.ok(withReference.thermalSignal.date>withReference.through);
assert.equal(decideThermal({archive:CLIMATE,regionId:'southeast',year:2027,nowDate:'2027-03-15',daily:days.slice(1),model:{state:'validated'}}).state,'unavailable','Missing a single day means no thermal date');
assert.equal(decideThermal({archive:CLIMATE,regionId:'southeast',year:2027,nowDate:'2027-10-15',daily:days,model:models.southeast}).state,'off','October cannot create spring warmth state');
const page=fs.readFileSync(new URL('../pages/michigan-trillium.js',import.meta.url),'utf8');
const comp=fs.readFileSync(new URL('../components/TrilliumThermal.js',import.meta.url),'utf8');
const api=fs.readFileSync(new URL('../pages/api/trillium-thermal.js',import.meta.url),'utf8');
const styles=fs.readFileSync(new URL('../public/trillium.css',import.meta.url),'utf8');
assert.ok(page.includes('initialThermalModels')&&page.includes('<TrilliumThermal regionId={selected}'),'Page SSR includes historical heat evidence');
assert.ok(api.includes('currentSeasonDays(')&&api.includes('models:\'era5\'')===false);
assert.ok(api.includes('forecast_days:8')&&api.includes('past_days:16')&&api.includes("models:'era5'"));
assert.ok(api.includes('s-maxage=21600')&&api.includes("local.month<3||local.month>6"));
assert.ok(comp.includes('ThermalCurve')&&comp.includes('tri-heat-chart')&&comp.includes('thermalSignal'));
assert.ok(styles.includes('.tri-thermal-panels')&&styles.includes('@media(max-width:740px)'));
console.log('Trillium thermal tests passed: 7 ERA5 regional histories, 56 springs, held-out advantage only where earned, 7-day forecasts, strict gaps, no off-season bloom.');
console.log('Observed held-out error days by region:',REGIONS.map(r=>r.id+'='+models[r.id].heatMae+'/'+models[r.id].calendarMae+'('+models[r.id].state+')').join(' '));
