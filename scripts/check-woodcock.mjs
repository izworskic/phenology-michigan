import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

// Test the source as a native ESM module without changing the Next.js repo module type.
const source=readFileSync(new URL('../lib/woodcock.js',import.meta.url),'utf8');
const m=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const sag=m.REGIONS.find(r=>r.id==='saginaw-bay');
const fall=new Date('2026-10-16T11:20:00Z');
assert.equal(m.michiganDate(fall),'2026-10-16');
assert.equal(m.upcomingDates(fall).length,7);
assert.equal(m.windowFor(sag,'2026-10-16').inSeason,false);
assert.equal(m.windowFor(sag,'2027-04-20').peak,true);
assert.equal(m.nextSpring(sag,fall).opens,'2027-03-20');
const sunset=m.sunsetUtc('2027-04-15',sag.lat,sag.lon);
assert.ok(sunset instanceof Date && Number.isFinite(sunset.getTime()));
const hour=Number(new Intl.DateTimeFormat('en-US',{timeZone:'America/Detroit',hour:'numeric',hourCycle:'h23'}).format(sunset));
assert.ok(hour>=19&&hour<=21,'Sunset should fall in the Michigan evening, got '+sunset.toISOString());
assert.equal(m.windMph('Calm'),0);
assert.equal(m.windMph('5 to 10 mph'),10);
assert.equal(m.windMph('4 to 7 km/h'),4);
assert.equal(m.windMph('Variable'),null);
assert.equal(m.weatherFit(39,3,5).score,0);
assert.equal(m.weatherFit(54,null,5).score,null);
assert.ok(m.weatherFit(52,4,10).score>m.weatherFit(52,20,80).score);
const base=m.nightFor(sag,'2027-04-15',[],[],new Date('2027-04-15T12:00:00Z'));
assert.equal(base.score,null);
assert.ok(base.startLabel&&base.endLabel);
assert.ok(base.cloudRule.includes('default'));
const start=new Date(base.start),cloudCover=[{validTime:new Date(start.getTime()-3600000).toISOString()+'/PT3H',value:90}];
const cloudy=m.nightFor(sag,'2027-04-15',[],cloudCover,new Date('2027-04-15T12:00:00Z'));
assert.equal(cloudy.clouds,90);
assert.equal(new Date(cloudy.start).getTime()-sunset.getTime(),15*60000);
const periods=[{startTime:new Date(sunset.getTime()).toISOString(),endTime:new Date(sunset.getTime()+3600000).toISOString(),temperature:52,windSpeed:'4 to 6 mph',probabilityOfPrecipitation:{value:10},shortForecast:'Partly Cloudy'}];
const good=m.nightFor(sag,'2027-04-15',periods,cloudCover,new Date('2027-04-15T12:00:00Z'));
assert.ok(good.score>=75&&good.tone==='good');
assert.equal(good.wind,6);assert.equal(good.pop,10);
const absent=m.regionalResult(sag,fall);
assert.equal(absent.status,'Off season');
assert.ok(absent.nights.every(n=>n.score==null));
const winter=m.regionalResult(sag,new Date('2027-01-15T17:00:00Z'));
assert.ok(winter.nights.every(n=>n.score==null));
console.log('Woodcock engine checks passed: dates, sunset, clouds, NWS hourly selection, wind, weather fit and off-season guard.');
