import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {SITES,BOARD_IDS,lookup,visibilityMiles,closestFrostSite,dawnDecision,evaluateGrid} from '../lib/frostMorning.mjs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
assert.equal(SITES.length,12);
assert.equal(BOARD_IDS.length,12,'Every mapped Michigan site must get statewide NWS conditions');
assert.deepEqual(BOARD_IDS,SITES.map(x=>x.id),'No map site omitted from ranking');
assert.equal(visibilityMiles(null,'wmoUnit:m'),null,'No visibility data cannot mean clear weather');
assert.equal(visibilityMiles(1609.344,'wmoUnit:m'),1);
assert.equal(visibilityMiles(1.609344,'wmoUnit:km'),1);
assert.equal(visibilityMiles(1,'wmoUnit:mi'),1);
assert.equal(visibilityMiles(5,'invalid'),null,'Unknown unit must fail closed');
assert.equal(visibilityMiles(-1,'wmoUnit:m'),null);
assert.equal(closestFrostSite(43.6,-83.9).id,'bay-city');
assert.equal(closestFrostSite(46.56,-87.39).id,'marquette');
assert.equal(closestFrostSite(35,-112),null,'Do not claim a Michigan forecast near Arizona');
assert.equal(closestFrostSite(100,-112),null,'Invalid latitude cannot select');
assert.equal(dawnDecision(null).level,'unavailable');
assert.equal(dawnDecision({score:84,photo:{status:'fog-watch'}}).level,'caution');
assert.equal(dawnDecision({score:84,photo:{status:'strong'}}).level,'promising');
assert.equal(dawnDecision({score:59,photo:{status:'possible'}}).level,'possible');
assert.equal(dawnDecision({score:49,photo:{status:'passed'}}).level,'past');
assert.equal(dawnDecision({score:95,photo:{status:'unavailable'}}).level,'unavailable','Strong score but incomplete sunrise data must not endorse a trip');
assert.equal(dawnDecision({score:10,photo:{status:'low'}}).level,'low');
const now=new Date('2026-10-17T04:00:00Z');
const validTime='2026-10-17T00:00:00+00:00/PT72H';
const field=(value,uom)=>({uom,values:[{validTime,value}]});
const grid={temperature:field(-1.7,'wmoUnit:degC'),dewpoint:field(-2.8,'wmoUnit:degC'),
  windSpeed:field(3,'wmoUnit:km_h-1'),skyCover:field(10,'wmoUnit:percent'),
  probabilityOfPrecipitation:field(0,'wmoUnit:percent')};
const normal=evaluateGrid(grid,now,lookup('bay-city'));
assert.equal(normal.mornings[0].photo.status,'strong','Missing optional visibility must not prevent a valid NWS frost-weather outlook');
assert.equal(normal.mornings[0].photo.visibilityMi,null);
const fog=evaluateGrid({...grid,visibility:field(1000,'wmoUnit:m')},now,lookup('bay-city'));
assert.equal(fog.mornings[0].photo.status,'fog-watch','Near-freezing visibility under a mile needs a caution, not enthusiastic photo advice');
assert.equal(dawnDecision(fog.mornings[0]).level,'caution');
assert.equal(fog.bestPhoto,null,'Low visibility must not lead to a top photography recommendation');
assert.equal(fog.mornings[0].photo.visibilityMi,.6);
const clear=evaluateGrid({...grid,visibility:field(10000,'wmoUnit:m')},now,lookup('bay-city'));
assert.equal(clear.mornings[0].photo.status,'strong','Clear visibility must not cause a fog warning');
const warm=evaluateGrid({...grid,temperature:field(10,'wmoUnit:degC'),visibility:field(1000,'wmoUnit:m')},now,lookup('bay-city'));
assert.notEqual(warm.mornings[0].photo.status,'fog-watch','Warm fog should not be classified as near-freezing rime risk');
const page=read('pages/frosty-mornings.js'),css=read('public/frosty-mornings.css');
const decision=read('components/FrostDawnDecision.js'),api=read('pages/api/frosty-mornings.js');
assert.ok(page.includes('<FrostDawnDecision'), 'Visible quick decision card required');
assert.ok(page.includes('navigator.geolocation.getCurrentPosition'),'Only visitor-initiated device location action');
assert.ok(page.includes('closestFrostSite('),'Nearest area must use bounded coordinate distance');
assert.ok(page.includes("setBoardAttempt(n=>n+1)"),'Failed state board should offer retry');
assert.ok(page.includes('{SITES.length}'),'Dynamic 12-site availability count');
assert.ok(page.includes('Fog/visibility')||decision.includes('Visibility:'),'Visibility disclaimer required');
assert.ok(decision.includes('Surface temperature unknown'),'Air forecast cannot masquerade as surface observations');
assert.ok(decision.includes('NWS alerts'),'Link to official warning source');
assert.ok(css.includes('.fm-dawn-decision'),'First-screen sunrise assessment needs responsive design');
assert.ok(css.includes('.fm-nearest-button'),'Opt-in proximity selector needs visible control');
assert.ok(api.includes('i+=4')&&api.includes('sites.slice(i,i+4)'), 'Bound NWS concurrency while fetching all sites');
assert.ok(api.includes('requested:sites.length'),'Expose complete board requested count');
assert.ok(api.includes('s-maxage=120'),'Cache full NWS outage only briefly');
console.log('Twelve-site coverage, weather-based sunrise guidance, low-visibility caution, proximity privacy and UI tests passed');
