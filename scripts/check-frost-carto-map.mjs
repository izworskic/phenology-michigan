import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {SITES} from '../lib/frostMorning.mjs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const map=read('components/FrostCartoMap.js');
const page=read('pages/frosty-mornings.js');
const css=read('public/frosty-mornings.css');
const sibling=read('components/FireflyCartoMap.js');
const key=s=>s.match(/const CARTO_(?:BASEMAP_)?KEY\s*=\s*['"]([^'"]+)['"]/);
assert.ok(key(map)&&key(sibling),'CARTO maps use an explicitly provisioned public tile key');
assert.equal(key(map)[1],key(sibling)[1],'Must reuse existing functioning CARTO key, not invent a new API key');
assert.ok(map.includes('https://basemaps.cartocdn.com/'),'Use genuine CARTO map tiles, not pseudo geography');
assert.ok(map.includes('rastertiles/voyager'),'Default labeled CARTO Voyager map required');
assert.ok(map.includes("'dark_all'"),'Offer CARTO night style');
assert.ok(map.includes('?key='),'Tile URL must include CARTO key or tiles will be watermarked');
assert.ok(map.includes('OpenStreetMap')&&map.includes('CARTO'),'Keep all required tile attribution visible');
assert.ok(map.includes('leaflet@1.9.4/dist/leaflet.js'),'Load matched Leaflet JS');
assert.ok(page.includes('leaflet@1.9.4/dist/leaflet.css'),'Load matched Leaflet CSS in Head');
assert.ok(page.includes("import FrostCartoMap from '../components/FrostCartoMap'"),'Import CARTO map component');
assert.ok(page.includes('<FrostCartoMap chosen={chosen} onChoose={choose} board={board?.locations} location={location}/>'),'Pass selected location and actual NWS board data to markers');
assert.ok(!page.includes('function MapPanel('),'Retire flat static SVG map');
assert.ok(!page.includes('great-lakes-context.geojson'),'No legacy pseudo map geometry');
assert.ok(map.includes("SITES.forEach(s=>"),'All tracked sites must participate in map');
assert.equal(SITES.length,12,'Preserve all forecast sites');
assert.ok(map.includes("marker.on('click'")&&map.includes("chooseRef.current(s.id)"),'Click must select forecast location');
assert.ok(map.includes('setTooltipContent(text)'),'Marker tooltip follows updated forecast scores');
assert.ok(map.includes('setIcon(icon('),'Marker appearance updates on NWS score or active site');
assert.ok(map.includes("selected===s.id")||map.includes("chosen===s.id"),'Selected marker stays highlighted');
assert.ok(map.includes('fitBounds(MICHIGAN_BOUNDS'),'Initial map and reset fit all Michigan');
assert.ok(map.includes('map.flyTo('),'Selecting a location pans and zooms the map');
assert.ok(map.includes('scrollWheelZoom:false'),'Map cannot trap ordinary page scroll');
assert.ok(map.includes('keyboard:true'),'Markers support keyboard access');
assert.ok(map.includes('new ResizeObserver'),'Resize detection is necessary in responsive layout');
assert.ok(map.includes('map.invalidateSize'),'Prevent blank halves or gray maps on resize');
assert.ok(map.includes("tiles.on('tileload',success)")&&map.includes("tiles.on('tileerror',failure)"),'Detect CARTO success/failure with genuine tile events');
assert.ok(map.includes('if(successes===0&&failures>0)'),'Do not declare service down if only one tile fails');
assert.ok(map.includes('Use the location list'),'Provide fallback if CARTO/Leaflet is unavailable');
assert.ok(map.includes('not observed hoarfrost'),'Forecast markers must not imply verified ice crystals');
assert.ok(map.includes('location?.id===s.id'),'Non-leaderboard sites update their own scores when selected');
assert.ok(css.includes('.fm-carto-frame{position:relative;height:492px'),'Map has concrete height, not a zero-height DIV');
assert.ok(css.includes('.fm-carto-canvas{position:absolute;inset:0'),'Leaflet gets a full-size viewport');
assert.ok(css.includes('.fm-carto-canvas img,.fm-carto-canvas .leaflet-tile{max-width:none!important;max-height:none!important}'),'Global responsive image CSS cannot distort map tiles');
assert.ok(css.includes('.fm-carto-canvas .leaflet-tile{width:256px!important;height:256px!important}'),'Leaflet raster tiles must be 256px');
assert.ok(css.includes('@media(max-width:650px){.fm-carto-frame{height:400px}'),'Real mobile map height required');
assert.ok(!css.includes('.fm-map svg'),'Do not carry the old pseudo map styles forward');
console.log('Michigan frosty morning CARTO Voyager map, data markers, interactions, attribution, failure states and mobile CSS verified');
