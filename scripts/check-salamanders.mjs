import assert from 'node:assert/strict';
import {REGIONS,forecastUrl,isSeason,nightKey,localDate,shiftDate,assessNight,thawContext,analyzeRegion,offlineRegion} from '../lib/salamanders.mjs';

assert.equal(REGIONS.length,9);
assert.equal(new Set(REGIONS.map(r=>r.id)).size,9);
assert.equal(isSeason(new Date('2026-10-16T12:00:00Z')),false);
assert.equal(isSeason(new Date('2027-03-22T12:00:00Z')),true);
assert.equal(localDate(new Date('2027-03-22T12:00:00Z')),'2027-03-22');
assert.equal(shiftDate('2027-03-01',-1),'2027-02-28');
assert.equal(nightKey('2027-03-22T20:00'),'2027-03-22');
assert.equal(nightKey('2027-03-23T02:00'),'2027-03-22');
assert.equal(nightKey('2027-03-23T09:00'),null);
assert.ok(forecastUrl().includes('timezone=America%2FDetroit'));
assert.ok(!REGIONS.some(r=>'pool' in r||'crossing' in r),'Locations may not expose pool or crossing sites');
assert.equal(offlineRegion(REGIONS[0]).nights.length,0);
const hours=(temp,rain)=>Array.from({length:10},()=>({temp,rain}));
const thaw={state:'suggestive'};
assert.equal(assessNight(hours(44,.25),thaw).level,'strong');
assert.equal(assessNight(hours(44,0),thaw).level,'dry');
assert.equal(assessNight(hours(32,.25),thaw).level,'cold');
assert.equal(assessNight(hours(44,.25),{state:'snow'}).level,'guarded');
assert.equal(assessNight(hours(44,null),thaw).level,'unknown');
assert.equal(assessNight(hours(44,.25).slice(0,2),thaw).level,'unknown');
const today='2027-04-10';
const times=[];for(let offset=-5;offset<8;offset++)for(let hour=0;hour<24;hour++)times.push(shiftDate(today,offset)+'T'+String(hour).padStart(2,'0')+':00');
const dailyTimes=Array.from({length:13},(_,i)=>shiftDate(today,i-5));
const sample={hourly:{time:times,temperature_2m:times.map(t=>t.includes(today)?45:37),rain:times.map(t=>(t.includes(today)&&Number(t.slice(11,13))>=18)?.3:0),snow_depth:times.map(()=>0)},daily:{time:dailyTimes,temperature_2m_max:dailyTimes.map(()=>51),temperature_2m_min:dailyTimes.map(()=>34)}};
const ctx=thawContext(sample,today);
assert.equal(ctx.state,'suggestive');
const out=analyzeRegion(REGIONS[0],sample,new Date('2027-04-10T12:00:00Z'));
assert.equal(out.nights.length,7);
assert.equal(out.nights[0].level,'strong');
assert.equal(out.best.date,today);
const missing=analyzeRegion(REGIONS[1],{},new Date('2027-04-10T12:00:00Z'));
assert.equal(missing.best,null);
assert.equal(missing.tonight.level,'unknown');
