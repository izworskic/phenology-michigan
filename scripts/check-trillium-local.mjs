import assert from 'node:assert/strict';
import fs from 'node:fs';
import {REGIONS,STOPS} from '../lib/trillium.mjs';
import {LOCAL_HABITATS,batchForecastUrl,parseGridPoint,assessDestination,buildLocalOutlook} from '../lib/trillium-local.mjs';
assert.equal(STOPS.length,10);assert.equal(REGIONS.length,7);
assert.deepEqual(Object.keys(LOCAL_HABITATS).sort(),STOPS.map(s=>s.id).sort(),'Every site needs a reviewed habitat note');
assert.ok(Object.values(LOCAL_HABITATS).every(h=>typeof h.note==='string'&&h.note.length>=45&&typeof h.kind==='string'&&h.kind.length>=8),'Each woodland needs a concrete descriptive note');
const url=new URL(batchForecastUrl(STOPS,REGIONS));
assert.equal(url.hostname,'api.open-meteo.com');
assert.equal(url.searchParams.get('forecast_days'),'7');
assert.equal(url.searchParams.get('timezone'),'America/Detroit');
assert.equal(url.searchParams.get('current'),'snow_depth');
assert.equal(url.searchParams.get('temperature_unit'),'fahrenheit');
assert.ok(url.searchParams.get('daily').includes('snowfall_sum'));
assert.equal(url.searchParams.get('latitude').split(',').length,17,'One batched request, not 17 fetches');
assert.equal(url.searchParams.get('longitude').split(',').length,17);
const date0='2027-05-10';
const days=Array.from({length:7},(_,i)=>new Date(Date.parse(date0+'T12:00:00Z')+i*86400000).toISOString().slice(0,10));
const raw=(mean=50,snowM=0.04)=>({latitude:44.5,longitude:-85.2,elevation:211,
 daily:{time:[...days],temperature_2m_mean:Array(7).fill(mean),temperature_2m_min:Array(7).fill(mean-20),
 temperature_2m_max:Array(7).fill(mean+14),snowfall_sum:[0,0,0,0,1,0,0]},
 current:{time:'2027-05-10T12:30',snow_depth:snowM}});
const parsed=parseGridPoint(raw(),date0);
assert.equal(parsed.days.length,7);
assert.equal(parsed.mean7F,50);
assert.equal(parsed.snowDepthCm,4);
assert.equal(parsed.snowDepthTime,'2027-05-10T12:30');
assert.equal(parsed.snowfall7Cm,1);
assert.equal(parsed.freezingNights,7);
assert.equal(parsed.mildDays,7);
assert.equal(parseGridPoint({...raw(),daily:{...raw().daily,time:days.slice(1)}},date0),null,'Short arrays do not count');
assert.equal(parseGridPoint({...raw(),daily:{...raw().daily,temperature_2m_min:[null,...Array(6).fill(30)]}},date0),null,'Missing weather is not zero');
assert.equal(parseGridPoint({...raw(),daily:{...raw().daily,time:[...days.slice(0,4),days[3],...days.slice(5)]}},date0),null,'Duplicate day rejected');
assert.equal(parseGridPoint(raw(), '2027-05-11'),null,'Stale forecast cannot be labeled current');
assert.equal(parseGridPoint({...raw(),current:{time:'2027-05-09T23:45',snow_depth:0.02}},date0).snowDepthCm,null,'Yesterday snow depth cannot be current');
assert.equal(parseGridPoint({...raw(),current:{time:'2027-05-10T13:00',snow_depth:null}},date0).snowDepthCm,null,'Unknown snow is not zero');
assert.equal(parseGridPoint({...raw(),current:{time:'2027-05-10T13:00',snow_depth:0}},date0).snowDepthCm,0);
const stop=STOPS.find(s=>s.id==='portage-point');
const regional=parseGridPoint(raw(46,0),date0);
const warm=assessDestination(stop,parsed,regional,date0);
assert.equal(warm.state,'available');assert.equal(warm.compare,'warmer');
assert.equal(warm.temperatureDeltaF,4);
assert.equal(warm.snow.state,'modeled_snow');
assert.equal(warm.snowDepthCm,4);
assert.ok(!JSON.stringify(warm).includes('bloom probability'),'Weather not a fake flower percentage');
assert.equal(assessDestination(stop,parseGridPoint(raw(45,0),date0),regional,date0).compare,'similar');
assert.equal(assessDestination(stop,parseGridPoint(raw(42,0),date0),regional,date0).compare,'cooler');
assert.equal(assessDestination(stop,parsed,null,date0).compare,null,'No guessed temperature delta when the region forecast fails');
const unknown=assessDestination(stop,null,regional,date0);
assert.equal(unknown.state,'unavailable');
assert.equal(unknown.compare,null);
assert.equal(assessDestination(stop,parseGridPoint({...raw(),current:{time:'2027-05-10T12:30',snow_depth:null}},date0),regional,date0).snow.state,'unknown');
const batch=[...STOPS.map(()=>raw(49,0)),...REGIONS.map(()=>raw(47,0))];
const result=buildLocalOutlook(STOPS,REGIONS,batch,date0);
assert.equal(result.length,10);
assert.ok(result.every(p=>p.compare==='warmer'&&p.snowDepthCm===0));
const incomplete=[...batch.slice(0,-1)];
assert.throws(()=>buildLocalOutlook(STOPS,REGIONS,incomplete,date0),'Never mis-map an incomplete multi-site response');
const broken=[...batch];broken[0]=null;
assert.equal(buildLocalOutlook(STOPS,REGIONS,broken,date0)[0].state,'unavailable');
const page=fs.readFileSync(new URL('../pages/michigan-trillium.js',import.meta.url),'utf8');
const api=fs.readFileSync(new URL('../pages/api/trillium-local.js',import.meta.url),'utf8');
const component=fs.readFileSync(new URL('../components/TrilliumLocalConditions.js',import.meta.url),'utf8');
const css=fs.readFileSync(new URL('../public/trillium.css',import.meta.url),'utf8');
assert.ok(api.includes("today.month<3||today.month>6")&&api.includes('batchForecastUrl(STOPS,REGIONS)')&&api.includes('buildLocalOutlook(STOPS,REGIONS'));
assert.ok(api.includes('s-maxage=21600')&&api.includes('fetch(url'));
assert.ok(page.includes("fetch('/api/trillium-local'")&&page.includes('LocalWeatherNote')&&page.includes('TrilliumLocalConditions'));
assert.ok(component.includes('tri-local-row')&&component.includes('tri-local-note')&&component.includes('vs region grid'));
assert.ok(css.includes('@media(max-width:680px)')&&css.includes('.tri-local-board'));
assert.ok(!api.includes('Math.random('),'No synthetic environmental readings');
console.log('Trillium local conditions: 17-grid single-call API, all 10 sites, snow uncertainty, seven-day temperature deltas, habitat labels, bad-data gates and mobile UI passed.');
