import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {SITES,BOARD_IDS,lookup,localParts,expandGrid,scoreHour,evaluateGrid,solarMorning,sunrisePhotoWindow} from '../lib/frostMorning.mjs';
assert.equal(SITES.length,12);
assert.equal(new Set(SITES.map(s=>s.id)).size,SITES.length);
assert.ok(SITES.every(s=>Number.isFinite(s.lat)&&Number.isFinite(s.lon)&&['America/Detroit','America/Chicago'].includes(s.tz)));
assert.equal(lookup('ironwood').tz,'America/Chicago','Western UP dawns follow Central Time');
assert.equal(BOARD_IDS.length,SITES.length,'Every CARTO map pin needs a statewide forecast, not just 9 of 12');
assert.ok(BOARD_IDS.every(id=>lookup(id)));
assert.equal(localParts(new Date('2026-10-17T11:00:00Z')).hour,7);
assert.equal(localParts(new Date('2026-11-01T12:00:00Z')).hour,7,'DST change must be local');
assert.equal(scoreHour({tempF:29,dewF:27,windMph:2,skyPct:12}).label,'Strong frost setup');
assert.ok(scoreHour({tempF:38,dewF:36,windMph:2,skyPct:10}).score<=40,'Air above 37 cannot become a strong frost prediction');
assert.ok(scoreHour({tempF:45,dewF:43,windMph:2,skyPct:10}).score<=10,'Warm morning blocks frost');
assert.ok(scoreHour({tempF:29,dewF:10,windMph:3,skyPct:10}).score<=42,'Dry air suppresses frost');
assert.equal(scoreHour({tempF:29,dewF:null,windMph:3,skyPct:10}),null,'Never score missing dew point');
assert.equal(scoreHour({tempF:29,dewF:26,windMph:null,skyPct:10}),null,'Never score missing wind');
assert.equal(scoreHour({tempF:29,dewF:26,windMph:3,skyPct:null}),null,'Never score missing sky cover');
assert.equal(scoreHour({tempF:29,dewF:26,windMph:3,skyPct:101}),null,'Invalid sky cover must not score');
const now=new Date('2026-10-17T04:00:00Z');
const validTime='2026-10-17T00:00:00+00:00/PT72H';
const field=(value,uom)=>({uom,values:[{validTime,value}]});
const grid={temperature:field(-1.7,'wmoUnit:degC'),dewpoint:field(-2.8,'wmoUnit:degC'),
  windSpeed:field(3,'wmoUnit:km_h-1'),skyCover:field(10,'wmoUnit:percent'),
  probabilityOfPrecipitation:field(0,'wmoUnit:percent'),relativeHumidity:field(93,'wmoUnit:percent')};
assert.equal(expandGrid(grid.temperature,now).size,70,'Only future and recently issued forecast hours are retained');
assert.equal(expandGrid({values:[{validTime,value:null}]},now).size,0,'Null NWS grid values are missing');
const report=evaluateGrid(grid,now,lookup('bay-city'));
assert.equal(report.coverage,3,'Three upcoming Michigan dawn windows should be scored');
assert.ok(report.best.score>=75,'Cold humid, calm clear morning should score highly');
assert.equal(report.best.bestHour,4,'First hour should win an equally favorable score');
assert.equal(report.mornings[0].date,'2026-10-17');
const incomplete=evaluateGrid({...grid,skyCover:{values:[]}},now,lookup('bay-city'));
assert.equal(incomplete.coverage,0,'Incomplete sky data must blank all scores');
const warm=evaluateGrid({...grid,temperature:field(8,'wmoUnit:degC')},now,lookup('bay-city'));
assert.ok(warm.best.score<=10,'Warm overnight weather cannot rank strongly');

const bay=lookup('bay-city');
const octSun=solarMorning('2026-10-18',bay);
assert.ok(octSun?.sunriseAt&&octSun?.civilDawnAt,'Valid Michigan sunrise and civil dawn required');
const solarFormat=iso=>new Intl.DateTimeFormat('en-US',{timeZone:'America/Detroit',hour:'2-digit',minute:'2-digit',hourCycle:'h23'}).format(new Date(iso));
const octRise=solarFormat(octSun.sunriseAt);
const octMinutes=Number(octRise.slice(0,2))*60+Number(octRise.slice(3));
assert.ok(Math.abs(octMinutes-(7*60+53))<=8,'Oct 18 Bay City sunrise should agree with published 7:53 EDT within 8 minutes');
assert.ok(Date.parse(octSun.civilDawnAt)<Date.parse(octSun.sunriseAt),'Civil twilight precedes sunrise');
const standardSun=solarMorning('2026-11-01',bay);
const oldOffset=(Date.parse(octSun.sunriseAt)-Date.parse('2026-10-18T07:53:00-04:00'));
assert.ok(Math.abs(oldOffset)<9*60*1000,'EDT conversion must preserve October sunrise');
assert.ok(Number(solarFormat(standardSun.sunriseAt).slice(0,2))>=6,'November DST sunrise must stay local, not UTC');
assert.ok(standardSun.sunriseAt.startsWith('2026-11-01'),'Sunrise date must agree with local date even across DST');
assert.equal(solarMorning('not-a-date',bay),null);
assert.equal(solarMorning('2026-02-30',bay),null);
assert.ok(report.bestPhoto,'Complete cold and clear NWS hours should create an upcoming photo viewing opportunity');
assert.equal(report.mornings[0].photo.status,'strong');
assert.ok(Date.parse(report.bestPhoto.photo.arriveAt)<Date.parse(report.bestPhoto.photo.sunriseAt));
assert.ok(Date.parse(report.bestPhoto.photo.windowStartAt)<Date.parse(report.bestPhoto.photo.windowEndAt));
const noSkyPhoto=incomplete.mornings[0].photo;
assert.equal(noSkyPhoto.status,'unavailable','No dawn viewing rating when cloud data is absent');
const expiredPhoto=sunrisePhotoWindow('2026-10-17',bay,report.mornings[0].hourly,new Date('2026-10-17T18:00:00Z'));
assert.equal(expiredPhoto.status,'passed','Do not advertise an expired photo window');
const oneHour=sunrisePhotoWindow('2026-10-17',bay,report.mornings[0].hourly.filter(h=>h.hour===7),now);
assert.equal(oneHour.status,'unavailable','Require forecast samples around both sides of sunrise');
const cloudyHours=report.mornings[0].hourly.map(h=>({...h,skyPct:100}));
assert.notEqual(sunrisePhotoWindow('2026-10-17',bay,cloudyHours,now).status,'strong','Overcast sunrise is not a promising light window');

