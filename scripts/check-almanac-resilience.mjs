import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const src=readFileSync(new URL('../lib/almanac.js',import.meta.url),'utf8');
const {snapshotNote,writeAlmanac,buildPrompt}=await import('data:text/javascript;base64,'+Buffer.from(src).toString('base64'));
const snap={date:'2026-11-26',airF:35,ausableFlow:781,gdd:0,birdCount:0,topBird:null};
const events=[{name:'Late waterfowl migration',cat:'birds',note:'usual timing'}];
const fallback=snapshotNote(snap,events,[]);
assert.equal(fallback.mode,'source-fallback');
assert.match(fallback.text,/781 cfs/);assert.match(fallback.text,/not observations made in the field/);
assert.match(fallback.text,/not what has been seen/);assert.match(fallback.text,/0/);
assert.equal(snapshotNote({date:snap.date,birdCount:0},[],[]).ok,false);
assert.doesNotMatch(buildPrompt(snap,events,[]),/Bird species reported nearby in the last day/);
const none=await writeAlmanac(snap,events,[],null,{env:{},fetchImpl:async()=>{throw Error('unexpected')}});
assert.equal(none.mode,'source-fallback');
let calls=[];
const ai='The record stands in late fall. '.repeat(12);
const result=await writeAlmanac(snap,events,[],null,{env:{ANTHROPIC_API_KEY_FALL_COLOR:'fixture-a',ANTHROPIC_API_KEY:'fixture-b'},fetchImpl:async(_,o)=>{const key=o.headers['x-api-key'];calls.push(key);return key==='fixture-a'?{status:401,ok:false}:{status:200,ok:true,json:async()=>({content:[{type:'text',text:ai}]})}}});
assert.deepEqual(calls,['fixture-a','fixture-b']);assert.equal(result.mode,'anthropic');
calls=[];
const down=await writeAlmanac(snap,events,[],null,{env:{ANTHROPIC_API_KEY_FALL_COLOR:'a',ANTHROPIC_API_KEY:'b'},fetchImpl:async(_,o)=>{calls.push(o.headers['x-api-key']);return {status:503,ok:false}}});
assert.deepEqual(calls,['a']);assert.equal(down.mode,'source-fallback');
const cron=readFileSync(new URL('../pages/api/cron.js',import.meta.url),'utf8');
assert.match(cron,/r\.ok \? await writeAlmanac/);assert.match(cron,/mode: note\.mode/);
console.log('Almanac resilience checks passed.');

const forecastOnly={date:snap.date,soilF:35,windSpeedMph:12,daylightH:9.3};
const forecastNote=snapshotNote(forecastOnly,[],[]);
assert.equal(forecastNote.ok,true);
assert.match(forecastNote.text,/Modeled soil temperature: 35 F/);
assert.match(forecastNote.text,/Forecast wind speed: 12 mph/);
assert.match(forecastNote.text,/Calculated daylight duration: 9.3 hours/);
assert.equal(snapshotNote({date:snap.date,daylightH:25,windSpeedMph:-1},[],[]).ok,false);
calls=[];
const denied=await writeAlmanac(forecastOnly,[],[],null,{env:{ANTHROPIC_API_KEY_FALL_COLOR:'a',ANTHROPIC_API_KEY:'b'},fetchImpl:async(_,o)=>{calls.push(o.headers['x-api-key']);return {status:403,ok:false}}});
assert.deepEqual(calls,['a']);assert.equal(denied.mode,'source-fallback');

assert.match(cron,/req\.query\?\.recovery === "1"/);
const recovery=cron.slice(cron.indexOf('if (req.query?.recovery'),cron.indexOf('const log = []'));
assert.match(recovery,/readHistory\(\)/);
assert.match(recovery,/snapshotNote\(snap,active,soon\)/);
assert.doesNotMatch(recovery,/writeAlmanac\(|fetchRegional\(|fetchForecast\(/);
assert.match(recovery,/current banked snapshot unavailable/);
assert.match(cron,/failures\.push\("almanac not written:/);
